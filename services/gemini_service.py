"""Google Gemini AI Service - Client management, multi-model fallback, vision & streaming."""

import re
from typing import Optional, Tuple

import streamlit as st
from google import genai
from google.genai import types

from config import CANDIDATE_MODELS, is_placeholder_key


@st.cache_resource(show_spinner=False)
def get_gemini_client(api_key: str) -> Optional[genai.Client]:
    """Create and cache the Google GenAI client instance."""
    if is_placeholder_key(api_key):
        return None
    try:
        return genai.Client(api_key=api_key.strip().strip("\"'"))
    except Exception:
        return None


def generate_content_with_fallback(
    client: genai.Client,
    contents: object,
    config: Optional[types.GenerateContentConfig] = None,
) -> Tuple[str, str]:
    """Generate content attempting candidate models in cascade order to mitigate quota limits."""
    last_err = None
    for model in CANDIDATE_MODELS:
        try:
            resp = client.models.generate_content(
                model=model,
                contents=contents,
                config=config,
            )
            if resp and resp.text:
                return resp.text, model
        except Exception as e:
            last_err = e
            continue
    if last_err:
        raise last_err
    return "I wasn't able to construct a response.", CANDIDATE_MODELS[0]


def generate_stream_with_fallback(
    client: genai.Client,
    contents: object,
    config: Optional[types.GenerateContentConfig] = None,
):
    """Generate streaming chunks attempting candidate models in order to avoid 503/429 errors."""
    last_err = None
    for model in CANDIDATE_MODELS:
        try:
            stream = client.models.generate_content_stream(
                model=model,
                contents=contents,
                config=config,
            )
            chunks = []
            for chunk in stream:
                if chunk.text:
                    chunks.append(chunk.text)

            if chunks:
                def chunk_generator():
                    for c in chunks:
                        yield c

                return chunk_generator(), model
        except Exception as e:
            last_err = e
            continue

    if last_err:
        raise last_err

    def empty_gen():
        yield "I wasn't able to construct a response."

    return empty_gen(), CANDIDATE_MODELS[0]


def test_gemini_connection(client: Optional[genai.Client]) -> Tuple[bool, str]:
    """Test live Google Gemini API connectivity without exposing API keys."""
    if not client:
        return (
            False,
            "No active Gemini key found. Please paste your GEMINI_API_KEY in `.streamlit/secrets.toml`.",
        )
    try:
        response_text, model_used = generate_content_with_fallback(
            client=client,
            contents="Ping",
        )
        if response_text:
            return True, f"Connection to Google Gemini ({model_used}) is active & working!"
        return False, "Connected to Gemini, but received empty response."
    except Exception as err:
        err_msg = str(err)
        sanitized = re.sub(r"AIza[0-9A-Za-z-_]{35}", "[REDACTED_API_KEY]", err_msg)
        return False, f"API Error: {sanitized}"


def build_gemini_history(messages: list) -> list:
    """Convert session messages into a clean alternating list of Google GenAI Content objects."""
    raw_contents = []
    for idx, m in enumerate(messages):
        role = "user" if m.get("role") == "user" else "model"
        if idx == 0 and role == "model":
            continue

        parts = []
        if m.get("image") is not None:
            parts.append(
                types.Part.from_bytes(
                    data=m["image"],
                    mime_type=m.get("mime_type") or "image/jpeg",
                )
            )
        if m.get("content"):
            parts.append(types.Part.from_text(text=str(m["content"])))

        if parts:
            raw_contents.append((role, parts))

    sanitized_contents = []
    for role, parts in raw_contents:
        if not sanitized_contents:
            if role != "user":
                continue
            sanitized_contents.append(types.Content(role=role, parts=parts))
        else:
            prev_content = sanitized_contents[-1]
            if prev_content.role == role:
                prev_content.parts.extend(parts)
            else:
                sanitized_contents.append(types.Content(role=role, parts=parts))

    return sanitized_contents


def get_latest_plan_text(messages: list) -> str:
    """Extract the most recent plan response generated by Nemo."""
    for msg in reversed(messages):
        if msg.get("role") == "assistant":
            content = str(msg.get("content", "")).strip()
            if "Hey" in content and "I'm Nemo" in content:
                continue
            if "Gemini Notice:" in content:
                continue
            if content:
                return content
    return ""
